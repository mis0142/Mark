#!/usr/bin/env python3
"""Scan a parent folder for project directories and update PROJECTS.md.

Dependency-free. Notes in the existing index are preserved by path.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from datetime import datetime
from pathlib import Path

MARKERS: list[tuple[str, str]] = [
    (".git", "Git"),
    ("package.json", "Node.js"),
    ("pnpm-workspace.yaml", "Node.js (monorepo)"),
    ("pom.xml", "Java (Maven)"),
    ("build.gradle", "Java/Kotlin (Gradle)"),
    ("build.gradle.kts", "Kotlin (Gradle)"),
    ("requirements.txt", "Python"),
    ("pyproject.toml", "Python"),
    ("Pipfile", "Python"),
    ("Cargo.toml", "Rust"),
    ("go.mod", "Go"),
    ("Gemfile", "Ruby"),
    ("composer.json", "PHP"),
    ("*.csproj", "C# / .NET"),
    ("*.sln", "C# / .NET"),
    ("CMakeLists.txt", "C/C++ (CMake)"),
    ("Makefile", "Make"),
]

HEADER = """# Project Index

Auto-generated by `scan_projects.py`. Re-run the scanner to refresh paths, types, and dates.
The **Notes** column is preserved across rescans — edit it freely.

## 每日流程

1. 早上打开清单，挑今天的专案
2. 做完在清单上记一笔
3. 关掉就收工

"""

TABLE_HEADER = (
    "| Project | Path | Type | Last Updated | Notes |\n"
    "| --- | --- | --- | --- | --- |\n"
)


def has_marker(directory: Path, pattern: str) -> bool:
    if "*" in pattern:
        return any(directory.glob(pattern))
    return (directory / pattern).exists()


def detect_types(directory: Path) -> str:
    found: list[str] = []
    seen: set[str] = set()
    for pattern, label in MARKERS:
        if has_marker(directory, pattern) and label not in seen:
            found.append(label)
            seen.add(label)
    return ", ".join(found) if found else "Unknown"


def is_project(directory: Path) -> bool:
    return any(has_marker(directory, pattern) for pattern, _ in MARKERS)


def last_updated(directory: Path) -> str:
    latest = directory.stat().st_mtime
    try:
        with os.scandir(directory) as entries:
            for entry in entries:
                try:
                    mtime = entry.stat(follow_symlinks=False).st_mtime
                except OSError:
                    continue
                if mtime > latest:
                    latest = mtime
    except OSError:
        pass
    return datetime.fromtimestamp(latest).strftime("%Y-%m-%d")


def discover_projects(parent: Path) -> list[Path]:
    projects: list[Path] = []
    try:
        children = sorted(
            (p for p in parent.iterdir() if p.is_dir() and not p.name.startswith(".")),
            key=lambda p: p.name.lower(),
        )
    except OSError as exc:
        print(f"error: cannot read {parent}: {exc}", file=sys.stderr)
        sys.exit(1)

    for child in children:
        if is_project(child):
            projects.append(child.resolve())
    return projects


def escape_cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ").strip()


def parse_existing_notes(markdown_path: Path) -> dict[str, str]:
    """Map absolute path -> notes from an existing PROJECTS.md table."""
    notes: dict[str, str] = {}
    if not markdown_path.is_file():
        return notes

    text = markdown_path.read_text(encoding="utf-8")
    row_re = re.compile(
        r"^\|\s*(.*?)\s*\|\s*(.*?)\s*\|\s*(.*?)\s*\|\s*(.*?)\s*\|\s*(.*?)\s*\|$"
    )
    for line in text.splitlines():
        if not line.startswith("|"):
            continue
        if line.startswith("| ---") or line.startswith("|---"):
            continue
        if line.startswith("| Project"):
            continue
        match = row_re.match(line)
        if not match:
            continue
        path = match.group(2).strip().replace("\\|", "|")
        note = match.group(5).strip().replace("\\|", "|")
        if path and path != "Path":
            notes[path] = note
    return notes


def render_index(projects: list[Path], notes_by_path: dict[str, str], parent: Path) -> str:
    lines = [HEADER]
    lines.append(f"_Parent folder:_ `{parent}`  \n")
    lines.append(f"_Last scan:_ {datetime.now().strftime('%Y-%m-%d %H:%M')}  \n\n")
    lines.append(TABLE_HEADER)

    if not projects:
        lines.append("| _(none found)_ |  |  |  |  |\n")
    else:
        for project in projects:
            path = str(project)
            name = project.name
            ptype = detect_types(project)
            updated = last_updated(project)
            note = notes_by_path.get(path, "")
            lines.append(
                "| {name} | {path} | {ptype} | {updated} | {note} |\n".format(
                    name=escape_cell(name),
                    path=escape_cell(path),
                    ptype=escape_cell(ptype),
                    updated=escape_cell(updated),
                    note=escape_cell(note),
                )
            )

    lines.append(
        "\n## How to refresh\n\n"
        "```bash\n"
        f"python3 scan_projects.py \"{parent}\"\n"
        "```\n"
    )
    return "".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Scan a parent folder and update PROJECTS.md with discovered projects."
    )
    parser.add_argument(
        "parent",
        nargs="?",
        default=".",
        help="Parent folder to scan (default: current directory)",
    )
    parser.add_argument(
        "-o",
        "--output",
        default="PROJECTS.md",
        help="Output markdown path (default: PROJECTS.md)",
    )
    args = parser.parse_args()

    parent = Path(args.parent).expanduser().resolve()
    if not parent.is_dir():
        print(f"error: not a directory: {parent}", file=sys.stderr)
        sys.exit(1)

    output = Path(args.output).expanduser().resolve()
    notes = parse_existing_notes(output)
    projects = discover_projects(parent)
    markdown = render_index(projects, notes, parent)
    output.write_text(markdown, encoding="utf-8")

    print(f"scanned: {parent}")
    print(f"found:   {len(projects)} project(s)")
    print(f"wrote:   {output}")
    for project in projects:
        print(f"  - {project.name} ({detect_types(project)})")


if __name__ == "__main__":
    main()
